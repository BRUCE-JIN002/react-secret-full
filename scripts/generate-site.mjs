import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, content) => { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), content); };
const manifest = JSON.parse(read('docs/examples/manifest.json'));
const registry = {};
const catalog = [];
const pageText = (title, body, source, demo) => {
  const frontmatter = `---\ntitle: ${JSON.stringify(title)}\nsource: ${JSON.stringify(source)}\n---\n\n`;
  const firstHeading = body.match(/^# .+\n/m);
  let output = body;
  if (demo && firstHeading) output = body.replace(/\n## /, `\n<DemoFrame example="${demo}" title="${title.replaceAll('"', '&quot;')}" />\n\n## `);
  return frontmatter + output;
};
for (const [key, entry] of Object.entries(manifest)) {
  const section = entry.source.startsWith('src/components/') ? 'components' : entry.source.startsWith('src/ts-projects/') ? 'projects' : 'ecosystem';
  const slug = key.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase()).replace(/^-/, '');
  const title = entry.title;
  write(`site/${section}/${slug}.md`, pageText(title, read(entry.readme), entry.readme, key));
  registry[key] = entry.source;
  catalog.push({ key, title, link: `/${section}/${slug}`, section, source: entry.readme });
}
const hooks = fs.readdirSync(path.join(root, 'src/hooks')).filter((folder) => fs.existsSync(path.join(root, 'src/hooks', folder, 'README.md')));
for (const folder of hooks.sort()) {
  const source = `src/hooks/${folder}/README.md`;
  const body = read(source);
  const title = body.match(/^# (.+)/m)?.[1] || folder;
  const key = folder;
  const demoPath = `src/hooks/${folder}/demo/index.tsx`;
  const hasDemo = fs.existsSync(path.join(root, demoPath));
  if (hasDemo) registry[key] = demoPath;
  let page = pageText(title, body, source, hasDemo ? key : undefined);
  const implementation = ['index.ts', 'index.tsx'].find((filename) => fs.existsSync(path.join(root, `src/hooks/${folder}`, filename)));
  if (implementation) page += `\n\n## 实现源码\n\n::: details 查看 ${folder} 的实现\n\n\`\`\`tsx\n${read(`src/hooks/${folder}/${implementation}`)}\n\`\`\`\n\n:::\n`;
  write(`site/hooks/${folder}.md`, page);
  catalog.push({ key, title, link: `/hooks/${folder}`, section: 'hooks', source });
}
for (const folder of ['copyToClipboard', 'keepAlive', 'mutateObserver', 'portal']) {
  const source = `src/components/${folder}/README.md`;
  const body = read(source);
  const title = body.match(/^# (.+)/m)[1];
  write(`site/components/${folder}.md`, pageText(title, body, source));
  catalog.push({ key: folder, title, link: `/components/${folder}`, section: 'foundations', source });
}
write('site/.vitepress/catalog.json', JSON.stringify(catalog, null, 2) + '\n');
write('src/playground/registry.ts', `// Generated by scripts/generate-site.mjs.\nimport { lazy, ComponentType } from 'react';\nexport const demos: Record<string, React.LazyExoticComponent<ComponentType>> = {\n${Object.entries(registry).map(([key, source]) => `  ${JSON.stringify(key)}: lazy(() => import(${JSON.stringify('../' + source.replace(/^src\//, '').replace(/\.(tsx?|jsx?)$/, ''))})),`).join('\n')}\n};\n`);
for (const [section, title, intro] of [
  ['hooks', '自定义 Hooks', '从状态管理到副作用处理，把重复逻辑提炼成可复用的 Hook。每篇文档包含用法、API 与实现源码。'],
  ['components', '组件实践', '从基础组件到复杂交互，在真实演示中理解状态、组合与复用。'],
  ['ecosystem', '生态探索', '通过动画、拖拽、流程图与状态管理示例，探索 React 的常用生态。'],
  ['projects', '综合项目', '把组件、Hooks 和第三方库组合起来，完成有状态、有交互的完整功能。']
]) {
  const entries = catalog.filter((item) => item.section === section || (section === 'components' && item.section === 'foundations'));
  write(`site/${section}/index.md`, `---\ntitle: ${title}\n---\n\n# ${title}\n\n${intro}\n\n共 **${entries.length}** 篇内容。\n\n` + entries.map((entry) => `- [${entry.title}](${entry.link})`).join('\n') + '\n');
}
const counts = Object.fromEntries(['hooks', 'components', 'ecosystem', 'projects'].map((section) => [section, catalog.filter((entry) => entry.section === section).length]));
write('site/index.md', `---
layout: home
title: 首页
hero:
  name: React Secret
  text: 从理解原理，<br>到写出好代码。
  tagline: 一起探索 React · Hooks、组件与工程实践
  image:
    src: /react-logo.png
    alt: React
  actions:
    - theme: brand
      text: 开始阅读
      link: /guide/getting-started
    - theme: alt
      text: 探索组件
      link: /components/min-calendar
    - theme: alt
      text: GitHub
      link: https://github.com/BRUCE-JIN002/react-secret-full
features:
  - title: 自定义 Hooks
    details: ${counts.hooks} 个实用 Hooks，理解状态、副作用与逻辑复用，让复杂问题变得简单。
    link: /hooks/
    linkText: 探索 Hooks
  - title: 组件实践
    details: ${counts.components} 个交互示例与 4 个基础组件，从 API 设计到具体实现，边看边动手。
    link: /components/
    linkText: 浏览组件
  - title: 生态探索
    details: 动画、拖拽、流程图与状态管理，${counts.ecosystem} 个示例带你走进 React 生态。
    link: /ecosystem/
    linkText: 了解更多
  - title: 从示例到项目
    details: 把知识串起来，通过综合项目掌握组件组合、交互设计与状态持久化。
    link: /projects/
    linkText: 开始实践
---
`);
fs.copyFileSync(path.join(root, 'public/logo512.png'), path.join(root, 'site/public/react-logo.png'));
write('site/public/robots.txt', 'User-agent: *\nAllow: /\nSitemap: https://bruce-jin002.github.io/sitemap.xml\n');
console.log(`Generated ${catalog.length} documentation pages and ${Object.keys(registry).length} React demos.`);
