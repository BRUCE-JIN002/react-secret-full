#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "docs/examples/manifest.json"), "utf8"));
const docs = Object.fromEntries(Object.entries(manifest).map(([key, entry]) => {
  if (!fs.existsSync(path.join(root, entry.source))) throw new Error(`Missing source: ${entry.source}`);
  return [key, fs.readFileSync(path.join(root, entry.readme), "utf8")];
}));
const output = `// Generated by npm run sync-docs. Edit the README files listed in docs/examples/manifest.json.\nexport const exampleDocs: Record<string, string> = ${JSON.stringify(docs, null, 2)};\n`;
const target = path.join(root, "src/constants/exampleDocs.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) {
    console.error("Example documentation is out of sync. Run npm run sync-docs.");
    process.exit(1);
  }
} else fs.writeFileSync(target, output);
console.log(`${Object.keys(docs).length} example documents verified.`);
